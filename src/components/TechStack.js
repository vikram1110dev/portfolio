export default function TechStack() {
  const containerRef = useRef(null);
  const isInView = useInView(containerRef, { once: true, margin: "-100px 0px" });
  const [activeCategory, setActiveCategory] = useState(0);

  const containerVariants = {
    hidden: { opacity: 0 },
    visible: {
      opacity: 1,
      transition: { staggerChildren: 0.08 },
    },
  };

  const itemVariants = {
    hidden: { opacity: 0, y: 20, scale: 0.95 },
    visible: {
      opacity: 1,
      y: 0,
      scale: 1,
      transition: { duration: 0.4, ease: "easeOut" },
    },
  };

  const getIcon = (skillName) => {
    const IconComponent = TechIcons[skillName];
    return IconComponent ? <IconComponent size={26} /> : <DefaultIcon size={26} />;
  };

  return (
    <section id="tech-stack" className={styles.techStack} ref={containerRef}>
      <div className={styles.bgGrid} />
      <div className={`container ${styles.techContainer}`}>
        <motion.div
          initial={{ opacity: 0, y: 30 }}
          animate={isInView ? { opacity: 1, y: 0 } : { opacity: 0, y: 30 }}
          transition={{ duration: 0.6 }}
          className={styles.header}
        >
          <span className="section-label">SKILLS</span>
          <h2 className={styles.heading}>Tech Stack</h2>
          <p className={styles.subheading}>
            Technologies I use to build robust software solutions.
          </p>
        </motion.div>

        <div className={styles.content}>
          <motion.div
            className={styles.categories}
            initial={{ opacity: 0 }}
            animate={isInView ? { opacity: 1 } : { opacity: 0 }}
            transition={{ duration: 0.5, delay: 0.2 }}
          >
            {portfolioData.skills.map((skillGroup, index) => (
              <button
                key={index}
                className={`${styles.categoryBtn} ${activeCategory === index ? styles.active : ""} interactive`}
                onClick={() => setActiveCategory(index)}
                data-hover-text="SELECT"
              >
                {activeCategory === index && (
                  <motion.div
                    className={styles.categoryIndicator}
                    layoutId="categoryIndicator"
                    transition={{ type: "spring", stiffness: 400, damping: 30 }}
                  />
                )}
                <span className={styles.categoryText}>
                  {skillGroup.category}
                </span>
              </button>
            ))}
          </motion.div>

          <AnimatePresence mode="wait">
            <motion.div
              className={styles.skillsGrid}
              key={activeCategory}
              variants={containerVariants}
              initial="hidden"
              animate="visible"
              exit={{ opacity: 0, transition: { duration: 0.15 } }}
            >
              {portfolioData.skills[activeCategory].items.map((skill) => (
                <motion.div
                  key={skill.name}
                  className={styles.skillCard}
                  variants={itemVariants}
                  whileHover={{ y: -4, transition: { duration: 0.2 } }}
                >
                  <div className={styles.skillIcon}>
                    {getIcon(skill.name)}
                  </div>
                  <div className={styles.skillInfo}>
                    <h3 className={styles.skillName}>{skill.name}</h3>
                    <p className={styles.skillDesc}>{skill.description}</p>
                  </div>
                  <div className={styles.skillCardGlow} />
                </motion.div>
              ))}
            </motion.div>
          </AnimatePresence>
        </div>
      </div>
    </section>
  );
}
